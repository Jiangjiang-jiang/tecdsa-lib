/// Non-interactive range proof that Bob's MtA ciphertext is correctly formed.
///
/// Bob knows $(b, \beta', r)$ s.t. $C_b = b \cdot C_a \oplus \text{Enc}_N(\beta'; r)$
/// and proves $|b| < q^3$.
///
/// **Statement:** $(C_a, C_b, N, N', h_1, h_2)$.
///
/// **Witness:** $(b, \beta', r)$.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BobProof {
    t: Integer,
    z: Integer,
    e: Integer,
    s: Integer,
    s1: Integer,
    s2: Integer,
    t1: Integer,
    t2: Integer,
}

impl BobProof {
    /// Generate Bob's range proof (without EC check).
    ///
    /// # Parameters
    /// - `a_encrypted`: Alice's ciphertext $C_a$
    /// - `mta_encrypted`: the MtA output ciphertext $C_b = b \cdot C_a \oplus \text{Enc}(\beta'; r)$
    /// - `b`: Bob's secret multiplier
    /// - `beta_prim`: the random value Bob adds (plaintext of the additive term)
    /// - `ek_n`: the Paillier modulus $N$
    /// - `ek_nn`: the Paillier modulus squared $N^2$
    /// - `ntilde`: the Ring-Pedersen auxiliary parameters
    /// - `r`: the Paillier encryption randomness used for $\text{Enc}(\beta')$
    /// - `rng`: a cryptographic RNG
    ///
    /// Returns `(proof, optional_u_point)`. When `check_ec` is true, `u_point`
    /// contains the blinding EC point needed for `BobProofExt`.
    #[allow(clippy::too_many_arguments)]
    pub fn prove<C>(
        a_encrypted: &Integer,
        mta_encrypted: &Integer,
        b: &Integer,
        beta_prim: &Integer,
        ek_n: &Integer,
        ek_nn: &Integer,
        ntilde: &NTildeParams,
        r: &Integer,
        check_ec: bool,
        rng: &mut impl rand_core::CryptoRngCore,
    ) -> (Self, Option<C::ProjectivePoint>)
    where
        C: TecdsaCurve,
        FieldBytesSize<C>: ModulusSize,
        <C as CurveArithmetic>::Scalar: PrimeField<Repr = FieldBytes<C>>,
        <C as CurveArithmetic>::ProjectivePoint: GroupEncoding,
    {
        let q = group_order_integer::<C>();
        let q3 = (&q * &q).complete() * &q;
        let q_N_tilde = (&q * &ntilde.N_tilde).complete();
        let q3_N_tilde = (&q3 * &ntilde.N_tilde).complete();
        let q2_N = (&q * &q).complete() * ek_n;

        // Round 1: sample blinding values
        let alpha = sample_below(&q3, rng);
        let beta = Integer::sample_in_mult_group_of(rng, ek_n);
        let gamma = sample_below(&q2_N, rng);
        let rho = sample_below(&q_N_tilde, rng);
        let rho_prim = sample_below(&q3_N_tilde, rng);
        let sigma = sample_below(&q_N_tilde, rng);
        let tau = sample_below(&q3_N_tilde, rng);

        // z = h1^b * h2^rho mod N_tilde
        let z = commitment_unknown_order(&ntilde.h1, &ntilde.h2, &ntilde.N_tilde, b, &rho);

        // z' = h1^alpha * h2^rho' mod N_tilde
        let z_prim =
            commitment_unknown_order(&ntilde.h1, &ntilde.h2, &ntilde.N_tilde, &alpha, &rho_prim);

        // t = h1^beta_prim * h2^sigma mod N_tilde
        let t =
            commitment_unknown_order(&ntilde.h1, &ntilde.h2, &ntilde.N_tilde, beta_prim, &sigma);

        // w = h1^gamma * h2^tau mod N_tilde
        let w_commit =
            commitment_unknown_order(&ntilde.h1, &ntilde.h2, &ntilde.N_tilde, &gamma, &tau);

        // v = C_a^alpha * (1 + gamma*N) * beta^N mod N^2
        let v = {
            let ca_alpha = pow_mod_signed(a_encrypted, &alpha, ek_nn);
            let g_gamma = ((&gamma * ek_n).complete() + Integer::one()).modulo(ek_nn);
            let beta_n = pow_mod_signed(&beta, ek_n, ek_nn);
            (ca_alpha * g_gamma % ek_nn * beta_n).modulo(ek_nn)
        };

        // Fiat-Shamir challenge
        let g_paillier = ek_n + Integer::one();
        let (e, check_u) = if check_ec {
            // Extended proof: include X = bG and u = alpha*G in the hash
            let b_scalar = integer_to_scalar::<C>(b);
            let alpha_scalar = integer_to_scalar::<C>(&alpha);
            let G = C::generator();
            let X = G * b_scalar;
            let u_point = G * alpha_scalar;
            let e = bob_challenge_ext::<C>(
                ek_n,
                &g_paillier,
                a_encrypted,
                mta_encrypted,
                &z,
                &z_prim,
                &t,
                &v,
                &w_commit,
                &X,
                &u_point,
            );
            (e, Some(u_point))
        } else {
            let e = bob_challenge(
                ek_n,
                &g_paillier,
                a_encrypted,
                mta_encrypted,
                &z,
                &z_prim,
                &t,
                &v,
                &w_commit,
            );
            (e, None)
        };

        // Round 2: compute responses
        let s = {
            let r_e = pow_mod_signed(r, &e, ek_n);
            (r_e * &beta).modulo(ek_n)
        };
        let s1 = (&e * b).complete() + &alpha;
        let s2 = (&e * &rho).complete() + &rho_prim;
        let t1 = (&e * beta_prim).complete() + &gamma;
        let t2 = (&e * &sigma).complete() + &tau;

        (
            BobProof {
                t,
                z,
                e,
                s,
                s1,
                s2,
                t1,
                t2,
            },
            check_u,
        )
    }

    /// Verify Bob's range proof (without EC check).
    ///
    /// # Parameters
    /// - `a_enc`: Alice's ciphertext $C_a$
    /// - `mta_out`: the MtA output ciphertext $C_b$
    /// - `ek_n`: the Paillier modulus $N$
    /// - `ek_nn`: the Paillier modulus squared $N^2$
    /// - `ntilde`: the Ring-Pedersen auxiliary parameters
    ///
    /// # Errors
    /// Returns `MtaRangeError::BobVerify` if the proof does not verify.
    pub fn verify<C>(
        &self,
        a_enc: &Integer,
        mta_out: &Integer,
        ek_n: &Integer,
        ek_nn: &Integer,
        ntilde: &NTildeParams,
    ) -> Result<(), MtaRangeError>
    where
        C: TecdsaCurve,
        FieldBytesSize<C>: ModulusSize,
        <C as CurveArithmetic>::Scalar: PrimeField<Repr = FieldBytes<C>>,
    {
        self.verify_inner::<C>(a_enc, mta_out, ek_n, ek_nn, ntilde, None)
    }

    /// Internal verification logic shared by `BobProof` and `BobProofExt`.
    fn verify_inner<C>(
        &self,
        a_enc: &Integer,
        mta_out: &Integer,
        ek_n: &Integer,
        ek_nn: &Integer,
        ntilde: &NTildeParams,
        check: Option<(&C::ProjectivePoint, &C::ProjectivePoint)>,
    ) -> Result<(), MtaRangeError>
    where
        C: TecdsaCurve,
        FieldBytesSize<C>: ModulusSize,
        <C as CurveArithmetic>::Scalar: PrimeField<Repr = FieldBytes<C>>,
        <C as CurveArithmetic>::ProjectivePoint: GroupEncoding,
    {
        let q = group_order_integer::<C>();
        let q3 = (&q * &q).complete() * &q;

        // Range check: s1 < q^3
        if self.s1 > q3 {
            return Err(MtaRangeError::BobVerify);
        }

        let neg_e = -self.e.clone();

        // Reconstruct z': z' = h1^s1 * h2^s2 * z^{-e} mod N_tilde
        let z_prim = {
            let h1_s1 = pow_mod_signed(&ntilde.h1, &self.s1, &ntilde.N_tilde);
            let h2_s2 = pow_mod_signed(&ntilde.h2, &self.s2, &ntilde.N_tilde);
            let z_neg_e = pow_mod_signed(&self.z, &neg_e, &ntilde.N_tilde);
            (h1_s1 * h2_s2 % &ntilde.N_tilde * z_neg_e).modulo(&ntilde.N_tilde)
        };

        // Reconstruct v: v = C_a^s1 * s^N * (1+t1*N) * C_b^{-e} mod N^2
        let v = {
            let ca_s1 = pow_mod_signed(a_enc, &self.s1, ek_nn);
            let s_n = pow_mod_signed(&self.s, ek_n, ek_nn);
            let g_t1 = ((&self.t1 * ek_n).complete() + Integer::one()).modulo(ek_nn);
            let mta_neg_e = pow_mod_signed(mta_out, &neg_e, ek_nn);
            (ca_s1 * s_n % ek_nn * g_t1 % ek_nn * mta_neg_e).modulo(ek_nn)
        };

        // Reconstruct w: w = h1^t1 * h2^t2 * t^{-e} mod N_tilde
        let w_commit = {
            let h1_t1 = pow_mod_signed(&ntilde.h1, &self.t1, &ntilde.N_tilde);
            let h2_t2 = pow_mod_signed(&ntilde.h2, &self.t2, &ntilde.N_tilde);
            let t_neg_e = pow_mod_signed(&self.t, &neg_e, &ntilde.N_tilde);
            (h1_t1 * h2_t2 % &ntilde.N_tilde * t_neg_e).modulo(&ntilde.N_tilde)
        };

        // Recompute challenge
        let g_paillier = ek_n + Integer::one();
        let e = match check {
            Some((X, u)) => bob_challenge_ext::<C>(
                ek_n,
                &g_paillier,
                a_enc,
                mta_out,
                &self.z,
                &z_prim,
                &self.t,
                &v,
                &w_commit,
                X,
                u,
            ),
            None => bob_challenge(
                ek_n,
                &g_paillier,
                a_enc,
                mta_out,
                &self.z,
                &z_prim,
                &self.t,
                &v,
                &w_commit,
            ),
        };

        if e != self.e {
            return Err(MtaRangeError::BobVerify);
        }

        Ok(())
    }
}

/// Compute the Fiat-Shamir challenge for Bob's basic proof.
#[allow(clippy::too_many_arguments)]
fn bob_challenge(
    N: &Integer,
    Gen: &Integer,
    a_enc: &Integer,
    mta_out: &Integer,
    z: &Integer,
    z_prim: &Integer,
    t: &Integer,
    v: &Integer,
    w: &Integer,
) -> Integer {
    let mut hasher = Sha256::new();
    hasher.update(N.to_bytes_msf());
    hasher.update(Gen.to_bytes_msf());
    hasher.update(a_enc.to_bytes_msf());
    hasher.update(mta_out.to_bytes_msf());
    hasher.update(z.to_bytes_msf());
    hasher.update(z_prim.to_bytes_msf());
    hasher.update(t.to_bytes_msf());
    hasher.update(v.to_bytes_msf());
    hasher.update(w.to_bytes_msf());
    Integer::from_bytes_msf(&hasher.finalize())
}

/// Compute the Fiat-Shamir challenge for Bob's extended proof (with EC check).
#[allow(clippy::too_many_arguments)]
fn bob_challenge_ext<C>(
    N: &Integer,
    Gen: &Integer,
    a_enc: &Integer,
    mta_out: &Integer,
    z: &Integer,
    z_prim: &Integer,
    t: &Integer,
    v: &Integer,
    w: &Integer,
    X: &C::ProjectivePoint,
    u: &C::ProjectivePoint,
) -> Integer
where
    C: CurveArithmetic,
    <C as CurveArithmetic>::ProjectivePoint: GroupEncoding,
{
    let mut hasher = Sha256::new();
    hasher.update(N.to_bytes_msf());
    hasher.update(Gen.to_bytes_msf());
    hasher.update(a_enc.to_bytes_msf());
    hasher.update(mta_out.to_bytes_msf());
    hasher.update(z.to_bytes_msf());
    hasher.update(z_prim.to_bytes_msf());
    hasher.update(t.to_bytes_msf());
    hasher.update(v.to_bytes_msf());
    hasher.update(w.to_bytes_msf());
    // Include EC points: X coordinates then Y coordinates
    // We use compressed encoding (GroupEncoding) for simplicity and correctness
    hasher.update(X.to_bytes().as_ref());
    hasher.update(u.to_bytes().as_ref());
    Integer::from_bytes_msf(&hasher.finalize())
}

// ============================================================================
// Bob's extended proof (with EC DLog check)
// ============================================================================

/// Bob's extended range proof, additionally proving $B = bG$ on the elliptic
/// curve. This is the "MtAwc" variant from GG18.
#[derive(Debug, Clone)]
pub struct BobProofExt<C: CurveArithmetic> {
    /// The underlying Bob proof.
    pub proof: BobProof,
    /// The blinding point $u = \alpha G$ (needed for EC verification).
    pub u: C::ProjectivePoint,
}

impl<C> Serialize for BobProofExt<C>
where
    C: CurveArithmetic,
    C::ProjectivePoint: GroupEncoding,
{
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        use serde::ser::SerializeStruct;
        let mut s = serializer.serialize_struct("BobProofExt", 2)?;
        s.serialize_field("proof", &self.proof)?;
        s.serialize_field("u", self.u.to_bytes().as_ref())?;
        s.end()
    }
}

impl<'de, C> Deserialize<'de> for BobProofExt<C>
where
    C: CurveArithmetic,
    C::ProjectivePoint: GroupEncoding,
{
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        #[derive(Deserialize)]
        struct Helper {
            proof: BobProof,
            u: Vec<u8>,
        }
        let h = Helper::deserialize(deserializer)?;
        let mut repr = <C::ProjectivePoint as GroupEncoding>::Repr::default();
        let repr_slice = repr.as_mut();
        if h.u.len() != repr_slice.len() {
            return Err(serde::de::Error::custom("invalid point length"));
        }
        repr_slice.copy_from_slice(&h.u);
        let point = Option::from(C::ProjectivePoint::from_bytes(&repr))
            .ok_or_else(|| serde::de::Error::custom("invalid point encoding"))?;
        Ok(BobProofExt {
            proof: h.proof,
            u: point,
        })
    }
}

impl<C> BobProofExt<C>
where
    C: TecdsaCurve,
    FieldBytesSize<C>: ModulusSize,
    <C as CurveArithmetic>::Scalar: PrimeField,
    <C as CurveArithmetic>::ProjectivePoint: GroupEncoding,
{
    /// Prove Bob's extended range proof.
    ///
    /// Same parameters as `BobProof::prove`, but always includes the EC check.
    #[allow(clippy::too_many_arguments)]
    pub fn prove(
        a_encrypted: &Integer,
        mta_encrypted: &Integer,
        b: &Integer,
        beta_prim: &Integer,
        ek_n: &Integer,
        ek_nn: &Integer,
        ntilde: &NTildeParams,
        r: &Integer,
        rng: &mut impl rand_core::CryptoRngCore,
    ) -> Self {
        let (proof, u) = BobProof::prove::<C>(
            a_encrypted,
            mta_encrypted,
            b,
            beta_prim,
            ek_n,
            ek_nn,
            ntilde,
            r,
            true,
            rng,
        );
        BobProofExt {
            proof,
            u: u.expect("check_ec=true always returns Some"),
        }
    }

    /// Verify Bob's extended range proof.
    ///
    /// # Parameters
    /// - `a_enc`: Alice's ciphertext $C_a$
    /// - `mta_out`: the MtA output ciphertext $C_b$
    /// - `ek_n`: the Paillier modulus $N$
    /// - `ek_nn`: $N^2$
    /// - `ntilde`: Ring-Pedersen auxiliary parameters
    /// - `X`: the claimed public key $X = bG$ (to be verified)
    ///
    /// # Errors
    /// Returns `MtaRangeError::BobVerify` if the proof does not verify.
    pub fn verify(
        &self,
        a_enc: &Integer,
        mta_out: &Integer,
        ek_n: &Integer,
        ek_nn: &Integer,
        ntilde: &NTildeParams,
        X: &C::ProjectivePoint,
    ) -> Result<(), MtaRangeError> {
        // First verify the underlying Bob proof with EC hash
        self.proof
            .verify_inner::<C>(a_enc, mta_out, ek_n, ek_nn, ntilde, Some((X, &self.u)))?;

        // EC check: s1 * G == e * X + u
        let s1_scalar = integer_to_scalar::<C>(&self.proof.s1);
        let e_scalar = integer_to_scalar::<C>(&self.proof.e);
        let G = C::generator();
        let lhs = G * s1_scalar;
        let rhs = *X * e_scalar + self.u;

        if lhs.to_bytes().as_ref() != rhs.to_bytes().as_ref() {
            return Err(MtaRangeError::BobVerify);
        }

        Ok(())
    }
}

