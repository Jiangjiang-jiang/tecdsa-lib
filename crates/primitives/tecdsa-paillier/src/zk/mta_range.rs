/// Error type for MtA range proof verification failures.
#[derive(Debug, thiserror::Error)]
pub enum MtaRangeError {
    /// Verification of Alice's range proof failed.
    #[error("Alice MtA range proof verification failed")]
    AliceVerify,
    /// Verification of Bob's range proof failed.
    #[error("Bob MtA range proof verification failed")]
    BobVerify,
}

// ---------------------------------------------------------------------------
// NTilde parameters (shared auxiliary commitment parameters)
// ---------------------------------------------------------------------------

/// Ring-Pedersen auxiliary parameters $(N', h_1, h_2)$ used as commitment
/// parameters in MtA range proofs. These are generated by a third party
/// (or the verifier) and shared publicly.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct NTildeParams {
    /// RSA modulus $N' = p' q'$.
    #[serde(with = "ser_integer")]
    pub N_tilde: Integer,
    /// First base $h_1$.
    #[serde(with = "ser_integer")]
    pub h1: Integer,
    /// Second base $h_2 = h_1^\lambda \bmod N'$.
    #[serde(with = "ser_integer")]
    pub h2: Integer,
}

// ============================================================================
// Alice's proof
// ============================================================================

/// Non-interactive range proof that Alice's Paillier ciphertext encrypts
/// a value $a$ with $|a| < q^3$.
///
/// **Statement:** $(C, N, N', h_1, h_2)$ where $C = \text{Enc}_N(a; r)$.
///
/// **Witness:** $(a, r)$.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AliceProof {
    z: Integer,
    e: Integer,
    s: Integer,
    s1: Integer,
    s2: Integer,
}

impl AliceProof {
    /// Generate Alice's range proof.
    ///
    /// # Parameters
    /// - `a`: the plaintext value
    /// - `cipher`: the Paillier ciphertext $C = \text{Enc}_N(a; r)$
    /// - `ek_n`: the Paillier modulus $N$
    /// - `ek_nn`: the Paillier modulus squared $N^2$
    /// - `ntilde`: the Ring-Pedersen auxiliary parameters
    /// - `r`: the Paillier encryption randomness
    /// - `rng`: a cryptographic RNG
    pub fn prove<C>(
        a: &Integer,
        cipher: &Integer,
        ek_n: &Integer,
        ek_nn: &Integer,
        ntilde: &NTildeParams,
        r: &Integer,
        rng: &mut impl rand_core::CryptoRngCore,
    ) -> Self
    where
        C: TecdsaCurve,
        FieldBytesSize<C>: ModulusSize,
        <C as CurveArithmetic>::Scalar: PrimeField<Repr = FieldBytes<C>>,
    {
        let q = group_order_integer::<C>();
        let q3 = (&q * &q).complete() * &q;
        let q_N_tilde = (&q * &ntilde.N_tilde).complete();
        let q3_N_tilde = (&q3 * &ntilde.N_tilde).complete();

        // Round 1: sample blinding values and compute commitments
        let alpha = sample_below(&q3, rng);
        let beta = Integer::sample_in_mult_group_of(rng, ek_n);
        let gamma = sample_below(&q3_N_tilde, rng);
        let rho = sample_below(&q_N_tilde, rng);

        // z = h1^a * h2^rho mod N_tilde
        let z = commitment_unknown_order(&ntilde.h1, &ntilde.h2, &ntilde.N_tilde, a, &rho);

        // u = (1 + N)^alpha * beta^N mod N^2
        //   = (1 + alpha*N) * beta^N mod N^2
        let g_paillier = ek_n + Integer::one();
        let u = {
            // (1 + N)^alpha = (1 + alpha*N) mod N^2 (binomial) — one mul, no modexp.
            let g_alpha = (Integer::one() + (&alpha * ek_n).complete()).modulo(ek_nn);
            let beta_n = pow_mod_signed(&beta, ek_n, ek_nn);
            (g_alpha * beta_n).modulo(ek_nn)
        };

        // w = h1^alpha * h2^gamma mod N_tilde
        let w = commitment_unknown_order(&ntilde.h1, &ntilde.h2, &ntilde.N_tilde, &alpha, &gamma);

        // Fiat-Shamir challenge
        let e = alice_challenge(ek_n, &g_paillier, cipher, &z, &u, &w);

        // Round 2: compute responses
        // s = r^e * beta mod N
        let s = {
            let r_e = pow_mod_signed(r, &e, ek_n);
            (r_e * &beta).modulo(ek_n)
        };
        // s1 = e*a + alpha
        let s1 = (&e * a).complete() + &alpha;
        // s2 = e*rho + gamma
        let s2 = (&e * &rho).complete() + &gamma;

        AliceProof { z, e, s, s1, s2 }
    }

    /// Verify Alice's range proof.
    ///
    /// # Parameters
    /// - `cipher`: the Paillier ciphertext $C$
    /// - `ek_n`: the Paillier modulus $N$
    /// - `ek_nn`: the Paillier modulus squared $N^2$
    /// - `ntilde`: the Ring-Pedersen auxiliary parameters
    ///
    /// # Errors
    /// Returns `MtaRangeError::AliceVerify` if the proof does not verify.
    pub fn verify<C>(
        &self,
        cipher: &Integer,
        ek_n: &Integer,
        ek_nn: &Integer,
        ntilde: &NTildeParams,
    ) -> Result<(), MtaRangeError>
    where
        C: TecdsaCurve,
        FieldBytesSize<C>: ModulusSize,
        <C as CurveArithmetic>::Scalar: PrimeField<Repr = FieldBytes<C>>,
    {
        let q = group_order_integer::<C>();
        let q3 = (&q * &q).complete() * &q;

        // Range check: s1 < q^3
        if self.s1 > q3 {
            return Err(MtaRangeError::AliceVerify);
        }

        // Reconstruct u: u = (1+N)^s1 * s^N * C^{-e} mod N^2
        let g_paillier = ek_n + Integer::one();
        let u = {
            // (1 + N)^s1 = (1 + s1*N) mod N^2 (binomial) — one mul, no modexp.
            let gs1 = (Integer::one() + (&self.s1 * ek_n).complete()).modulo(ek_nn);
            let s_n = pow_mod_signed(&self.s, ek_n, ek_nn);
            let neg_e = -self.e.clone();
            let c_neg_e = pow_mod_signed(cipher, &neg_e, ek_nn);
            (gs1 * s_n % ek_nn * c_neg_e).modulo(ek_nn)
        };

        // Reconstruct w: w = h1^s1 * h2^s2 * z^{-e} mod N_tilde
        let w = {
            let h1_s1 = pow_mod_signed(&ntilde.h1, &self.s1, &ntilde.N_tilde);
            let h2_s2 = pow_mod_signed(&ntilde.h2, &self.s2, &ntilde.N_tilde);
            let neg_e = -self.e.clone();
            let z_neg_e = pow_mod_signed(&self.z, &neg_e, &ntilde.N_tilde);
            (h1_s1 * h2_s2 % &ntilde.N_tilde * z_neg_e).modulo(&ntilde.N_tilde)
        };

        // Recompute challenge
        let e = alice_challenge(ek_n, &g_paillier, cipher, &self.z, &u, &w);

        if e != self.e {
            return Err(MtaRangeError::AliceVerify);
        }

        Ok(())
    }
}

/// Compute the Fiat-Shamir challenge for Alice's proof.
fn alice_challenge(
    N: &Integer,
    Gen: &Integer,
    cipher: &Integer,
    z: &Integer,
    u: &Integer,
    w: &Integer,
) -> Integer {
    let mut hasher = Sha256::new();
    hasher.update(N.to_bytes_msf());
    hasher.update(Gen.to_bytes_msf());
    hasher.update(cipher.to_bytes_msf());
    hasher.update(z.to_bytes_msf());
    hasher.update(u.to_bytes_msf());
    hasher.update(w.to_bytes_msf());
    Integer::from_bytes_msf(&hasher.finalize())
}

