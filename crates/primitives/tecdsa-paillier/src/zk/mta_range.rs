//! Zero-knowledge range proofs for the Multiplicative-to-Additive (MtA) protocol.
//!
//! These proofs are described in Appendix A of <https://eprint.iacr.org/2019/114.pdf>
//! (GG18/GG20). They use Ring-Pedersen commitments with auxiliary parameters
//! $(N', h_1, h_2)$ to prove that a Paillier plaintext is in a bounded range.
//!
//! Two proofs are provided:
//!
//! - **`AliceProof`**: Alice sends $C = \text{Enc}_N(a; r)$ and proves
//!   $|a| < q^3$ where $q$ is the EC group order.
//!
//! - **`BobProof`**: Bob receives $C_a = \text{Enc}_N(a)$, computes
//!   $C_b = b \cdot C_a \oplus \text{Enc}_N(\beta'; r)$ and proves knowledge
//!   of $(b, \beta', r)$ with $|b| < q^3$. An extended variant `BobProofExt`
//!   additionally proves $B = bG$ on the elliptic curve.
//!
//! The proofs are non-interactive via the Fiat-Shamir transform (SHA-256).

#![allow(non_snake_case)]

